public class YearlyMaintenanceCost {
    static void main() {
        int winterCost = 1500;
        int springCost = 1600;
        int summerCost = 1700;
        int fallCost = 1800;
        int totalCost;
        totalCost = winterCost + springCost + summerCost + fallCost;
        System.out.println("The winter cost was " + winterCost);
        System.out.println("The spring cost was " + springCost);
        System.out.println("The summer cost was " + summerCost);
        System.out.println("The fall cost was " + fallCost);
        System.out.println("So, the total yearly maintenance cost is " + totalCost);
    }
}
